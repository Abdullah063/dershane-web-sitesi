#!/usr/bin/env python3
"""Build the existing static pages from shared partials; no third-party packages."""
import argparse
import json
from pathlib import Path
import re
import sys
from local_seo import apply_seo
from optimize_page import improve, defer_scripts
from clean_urls import output_path, public_path, rewrite_page, legacy_redirect

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'site-src'
TOKEN = re.compile(r'\{\{([\w:-]+)\}\}')


def render_source(path, metadata):
    page = (SOURCE / 'pages' / (path + '.template')).read_text()
    def include(match):
        key = match[1]
        if key.startswith('include:'):
            name = key.split(':', 1)[1]
            return (SOURCE / 'partials' / (name + '.html.template')).read_text()
        return match[0]
    page = TOKEN.sub(include, page)
    values = {**json.loads((SOURCE / 'site.json').read_text()), **metadata.get('values', {})}
    page = TOKEN.sub(lambda m: values.get(m[1], m[0]), page)
    prefix = '../' * (len(Path(path).parts) - 1)
    page = page.replace('{{root}}', prefix)
    unresolved = TOKEN.findall(page)
    if unresolved:
        raise ValueError(f'{path}: unresolved template fields: {unresolved}')
    page = improve(apply_seo(page, path, SOURCE), path, ROOT, SOURCE)
    # Share the small consent stylesheet across the page-specific CSS bundles.
    return page.replace('</head>', f'<link rel="stylesheet" href="{prefix}assets/kuantum/analytics.css?v=2">\n</head>')


def render(path, metadata):
    pages = json.loads((SOURCE / 'pages.json').read_text())
    return defer_scripts(rewrite_page(render_source(path, metadata), path, pages, aliases=json.loads((SOURCE / 'seo.json').read_text())['aliases']), output_path(path), ROOT)


def generated_files(pages):
    outputs = {output_path(path): render(path, data) for path, data in pages.items()}
    for path in pages:
        if output_path(path) != path:
            outputs[path] = legacy_redirect(path)
    # Apache redirects: THE_REQUEST prevents redirecting the internal directory index.
    rules = ['# Generated by scripts/build_site.py; preserve unrelated hosting rules.',
             '<IfModule mod_rewrite.c>', 'RewriteEngine On']
    for path in pages:
        escaped = re.escape(path)
        rules += [r'RewriteCond %{THE_REQUEST} "\s/+[^?\ ]*' + escaped + r'(?:[?\ ]|$)" [NC]',
                  'RewriteRule ^' + escaped + '$ ' + ('./' if not public_path(path) else public_path(path)) + ' [R=301,L,NE]']
    rules += ['</IfModule>', '']
    rules += (SOURCE / 'hosting-performance.conf').read_text().splitlines()
    outputs['.htaccess'] = '\n'.join(rules)
    # Use canonical URLs, so alternate copies of course pages are not duplicated.
    from html import unescape, escape
    canonical = set()
    seo = json.loads((SOURCE / 'seo.json').read_text())
    for path in pages:
        if path in seo['aliases'] or not seo['pages'][path]['index']:
            continue
        match = re.search(r'<link[^>]*rel="canonical"[^>]*href="([^"]+)"',outputs[output_path(path)])
        if match:
            canonical.add(unescape(match[1]))
    outputs['sitemap.xml'] = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + ''.join('<url><loc>'+escape(url)+'</loc></url>\n' for url in sorted(canonical)) + '</urlset>\n'
    outputs['robots.txt'] = 'User-agent: *\nAllow: /\nDisallow: /site-src/\nDisallow: /scripts/\nSitemap: https://kuantumsayisalakademi.com/sitemap.xml\n'

    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check output without writing files')
    args = parser.parse_args()
    pages = json.loads((SOURCE / 'pages.json').read_text())
    # Render everything before writing, so a template error cannot leave half a build.
    outputs = generated_files(pages)
    stale = []
    for path, html in outputs.items():
        target = ROOT / path
        if target.exists() and target.read_text() == html:
            continue
        stale.append(path)
        if not args.check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(html)
    if args.check and stale:
        print('Rebuild required:\n' + '\n'.join(stale), file=sys.stderr)
        return 1
    print(f'{len(pages)} pages checked; {len(stale)} ' + ('outdated.' if args.check else 'updated.'))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
